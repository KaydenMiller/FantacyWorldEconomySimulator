namespace WorldEcon.Gui.Tests.Unit;

/// <summary>Error paths of the main view-model (review findings A1, A2, A6, A8, A9).</summary>
[NotInParallel]
public class ErrorHandlingTests
{
    private static readonly WorldGenSettings Small = new() { Grid = new() { Frequency = 8, RegionMultiplier = 2, TileMultiplier = 2 } };

    private static string TempDir()
    {
        var dir = Path.Combine(Path.GetTempPath(), $"worldecon_gui_err_{Guid.NewGuid():N}");
        Directory.CreateDirectory(dir);
        return dir;
    }

    private static void Delete(string dir)
    {
        SqliteConnection.ClearAllPools();
        Directory.Delete(dir, recursive: true);
    }

    private static async Task<string> SeededDbAsync(string dir)
    {
        var db = Path.Combine(dir, "world.db");
        await DemoSeeder.CreateAsync(db, Small);
        SqliteConnection.ClearAllPools();
        return db;
    }

    private static async Task ExecAsync(string db, string sql)
    {
        await using var conn = new SqliteConnection($"Data Source={db};Pooling=False");
        await conn.OpenAsync();
        await using var cmd = conn.CreateCommand();
        cmd.CommandText = sql;
        await cmd.ExecuteNonQueryAsync();
    }

    [Test]
    public async Task Opening_a_database_with_malformed_settings_json_reports_the_error_and_does_not_throw()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            await ExecAsync(db, "UPDATE worldgen_runs SET SettingsJson = '{not json'");
            var vm = new MainViewModel();

            var ok = await vm.OpenAsync(db);

            ok.Should().BeFalse();
            vm.HasWorld.Should().BeFalse();
            vm.StatusText.Should().StartWith($"Could not open {db}:");
            vm.ErrorText.Should().Contain("Could not open").And.Contain("world.db");
            vm.IsBusy.Should().BeFalse();
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task Opening_a_world_from_an_older_generator_asks_to_regenerate()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            await ExecAsync(db, $"UPDATE worldgen_runs SET GeneratorVersion = {WorldGenerator.GeneratorVersion - 1}, SettingsJson = '{{\"Biomes\": {{\"MountainReliefM\": 1500}}}}'");
            var vm = new MainViewModel();

            (await vm.OpenAsync(db)).Should().BeFalse();

            vm.ErrorText.Should().Contain($"world generated by generator v{WorldGenerator.GeneratorVersion - 1}; this build is v{WorldGenerator.GeneratorVersion} — regenerate the world");
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task Opening_a_database_with_an_old_schema_adds_the_regenerate_hint()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            await ExecAsync(db, "DROP TABLE globe_cells");
            var vm = new MainViewModel();

            (await vm.OpenAsync(db)).Should().BeFalse();

            vm.ErrorText.Should().Contain("no such table").And.Contain(MainViewModel.RegenerateHint);
        }
        finally { Delete(dir); }
    }

    [Test]
    public void An_area_with_no_cells_shows_no_cells_and_does_not_throw()
    {
        var empty = new GeneratedArea(0, GeographicRegionKind.Plain, "Nowhere", []);
        var l = TestWorlds.Loaded.Layers;

        var rows = DetailFormatter.Area(empty, l);

        rows.Should().Contain(new DetailRow("Cells", "no cells"));

        var generated = WorldGenerator.Generate(42, TestWorlds.Settings);
        generated.Layers.Areas = [empty];
        var world = World.Create("Empty", 42UL, CalendarDefinition.Default, "1.0.0").Value;
        var vm = new MainViewModel();
        vm.UseSession(new WorldSession(LoadedGlobe.FromGenerated(world, generated, TestWorlds.Settings, []), path: null));
        var act = () => vm.Areas.SelectedArea = vm.Areas.Items[0];
        act.Should().NotThrow();
        vm.AreaDetailRows.Should().Contain(new DetailRow("Cells", "no cells"));
    }

    [Test]
    public async Task A_failed_demo_world_leaves_no_file_and_an_existing_file_is_untouched()
    {
        var dir = TempDir();
        try
        {
            var vm = new MainViewModel();
            var invalid = new WorldGenSettings { Grid = new() { Frequency = 0 } };
            var fresh = Path.Combine(dir, "fresh.db");

            (await vm.CreateDemoWorldAsync(fresh, invalid)).Should().BeFalse();

            File.Exists(fresh).Should().BeFalse("a failed seeding deletes the partial file");
            Directory.GetFiles(dir).Should().BeEmpty("no temporary file is left behind");
            vm.ErrorText.Should().Contain("Could not create");

            var existing = Path.Combine(dir, "existing.db");
            await File.WriteAllTextAsync(existing, "keep me");
            (await vm.CreateDemoWorldAsync(existing, invalid, overwrite: true)).Should().BeFalse();
            (await File.ReadAllTextAsync(existing)).Should().Be("keep me", "the old file is replaced only after seeding succeeds");
            Directory.GetFiles(dir).Should().Equal(existing);
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task A_confirmed_overwrite_replaces_the_existing_file_with_the_demo_world()
    {
        var dir = TempDir();
        try
        {
            var existing = Path.Combine(dir, "existing.db");
            await File.WriteAllTextAsync(existing, "old contents");
            var vm = new MainViewModel();

            (await vm.CreateDemoWorldAsync(existing, Small)).Should().BeFalse("without the overwrite confirmation an existing file is kept");
            (await File.ReadAllTextAsync(existing)).Should().Be("old contents");

            (await vm.CreateDemoWorldAsync(existing, Small, overwrite: true)).Should().BeTrue(vm.StatusText);

            vm.HasWorld.Should().BeTrue();
            vm.Session!.Layers.Grid.Frequency.Should().Be(8);
            vm.ErrorText.Should().BeEmpty();
            SqliteConnection.ClearAllPools();
            Directory.GetFiles(dir).Should().Equal(existing);
        }
        finally { Delete(dir); }
    }

    /// <summary>
    /// Review finding I2: File → New world over the open file closes the open world (renderer disposed, tile source
    /// closed) before the file is replaced, so the old map can never read the new world's tile blocks.
    /// </summary>
    [Test]
    public async Task Overwriting_the_open_file_closes_the_old_world_before_the_file_is_replaced()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            var vm = new MainViewModel();
            (await vm.OpenAsync(db)).Should().BeTrue(vm.StatusText);
            var old = vm.Session!;
            vm.Map!.ZoomToLevel(WorldEcon.Rendering.MapLevel.Detail);
            await vm.Map.LoadVisibleTilesAsync();
            var written = File.GetLastWriteTimeUtc(db);
            DateTime? writtenWhenClosed = null;
            vm.PropertyChanged += (_, e) =>
            {
                if (e.PropertyName == nameof(MainViewModel.Session) && vm.Session is null) writtenWhenClosed = File.GetLastWriteTimeUtc(db);
            };

            var other = Small with { Grid = Small.Grid with { PlanetRadiusKm = 4000 } };
            (await vm.CreateDemoWorldAsync(db, other, overwrite: true)).Should().BeTrue(vm.StatusText);

            writtenWhenClosed.Should().Be(written, "the old world is detached before the file is replaced");
            old.IsClosed.Should().BeTrue();
            var uncached = Enumerable.Range(0, old.Layers.Grid.CellCount).First(c => old.Renderer.Cache!.StateOf(c) == WorldEcon.Rendering.TileBlockState.NotLoaded);
            var read = () => old.TileBlockAsync(uncached);
            await read.Should().ThrowAsync<ObjectDisposedException>("a closed world's tile source refuses reads");
            var draw = () =>
            {
                using var bmp = new SkiaSharp.SKBitmap(8, 8);
                using var canvas = new SkiaSharp.SKCanvas(bmp);
                old.Renderer.Draw(canvas, vm.Map!.View, vm.Map.DrawOptions);
            };
            draw.Should().Throw<ObjectDisposedException>();
            vm.Session.Should().NotBeSameAs(old);
            vm.Session!.Data.Settings.Grid.PlanetRadiusKm.Should().Be(4000);
            (await vm.Session.TileBlockAsync(0)).Should().NotBeNull("the new world reads its own blocks");
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task Overwriting_the_open_file_through_a_symbolic_link_closes_the_old_world()
    {
        if (OperatingSystem.IsWindows()) return; // creating symbolic links needs a privilege on Windows
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            var link = Path.Combine(dir, "link.db");
            File.CreateSymbolicLink(link, db);
            MainViewModel.SameFile(link, db).Should().BeTrue();
            MainViewModel.SameFile(Path.Combine(dir, ".", "link.db"), db).Should().BeTrue();
            MainViewModel.SameFile(Path.Combine(dir, "other.db"), db).Should().BeFalse();

            var vm = new MainViewModel();
            (await vm.OpenAsync(link)).Should().BeTrue(vm.StatusText);
            var old = vm.Session!;
            (await vm.CreateDemoWorldAsync(db, Small, overwrite: true)).Should().BeTrue(vm.StatusText);
            old.IsClosed.Should().BeTrue("the open world's file is the target, reached through a link");
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task A_failed_replace_of_the_open_file_opens_the_previous_world_again()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            var vm = new MainViewModel();
            (await vm.OpenAsync(db)).Should().BeTrue(vm.StatusText);
            var seed = vm.Session!.Data.World.Seed;
            // When the open world is closed for the replace, remove the seeded temporary file: the move then throws.
            vm.PropertyChanged += (_, e) =>
            {
                if (e.PropertyName != nameof(MainViewModel.Session) || vm.Session is not null) return;
                foreach (var tmp in Directory.GetFiles(dir, "*.tmp")) File.Delete(tmp);
            };

            (await vm.CreateDemoWorldAsync(db, Small with { Grid = Small.Grid with { PlanetRadiusKm = 4000 } }, overwrite: true)).Should().BeFalse();
            vm.ErrorText.Should().Contain("The previous world was opened again");
            vm.Session.Should().NotBeNull();
            vm.Session!.Data.World.Seed.Should().Be(seed);
            vm.Session.Data.Settings.Grid.PlanetRadiusKm.Should().NotBe(4000);
            (await vm.Session.TileBlockAsync(0)).Should().NotBeNull();
        }
        finally { Delete(dir); }
    }

    [Test]
    public async Task File_actions_are_disabled_while_busy()
    {
        var dir = TempDir();
        try
        {
            var db = await SeededDbAsync(dir);
            var vm = new MainViewModel();
            vm.CanUseFileActions.Should().BeTrue();

            var first = vm.OpenAsync(db);
            vm.IsBusy.Should().BeTrue();
            vm.CanUseFileActions.Should().BeFalse();
            (await vm.OpenAsync(db)).Should().BeFalse("a second open while busy is refused");
            (await vm.CreateDemoWorldAsync(Path.Combine(dir, "other.db"), Small)).Should().BeFalse();

            (await first).Should().BeTrue(vm.StatusText);
            vm.CanUseFileActions.Should().BeTrue();
            File.Exists(Path.Combine(dir, "other.db")).Should().BeFalse();
        }
        finally { Delete(dir); }
    }
}
